function getImmersiveScript(id) {
  if (!id) return null;
  /* 优先取当前冒险缓存的剧本对象（随机剧本不在 IMMERSIVE_SCRIPTS 常量里，必须走缓存） */
  const st = appData.immersiveFocus;
  if (st && st.script && idEq(st.script.id, id)) return st.script;
  /* 内置剧本库 */
  const fixed = IMMERSIVE_SCRIPTS.find(function (s) {
    return idEq(s.id, id);
  });
  if (fixed) return fixed;
  /* 用户导入的剧情副本（独立存储，见 01-data.js） */
  const imp = importedScriptById(id);
  return imp ? imp.script : null;
}
