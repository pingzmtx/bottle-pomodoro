/* 环境音：简单星际/自然白噪音（WebAudio 生成，低音量循环），全局静音时尊重不播 */
let _ambientNode = null,
  _ambientGain = null;
function startAmbientNoise() {
  if (appData.settings.sound) return; /* 全局静音 */
  try {
    /* ★ audioCtx 的真身在 01b，这里是导入绑定（只读）——`audioCtx = new ...` 会抛
       TypeError: Assignment to constant variable，于是环境音整段 try 被吃掉、永远没声音。
       写走 __set_audioCtx（读仍是活绑定）。 */
    if (!audioCtx) __set_audioCtx(new (window.AudioContext || window.webkitAudioContext)());
    if (audioCtx.state === 'suspended') audioCtx.resume();
    if (_ambientNode) return;
    const size = 2 * audioCtx.sampleRate;
    const buffer = audioCtx.createBuffer(1, size, audioCtx.sampleRate);
    const data = buffer.getChannelData(0);
    let last = 0;
    for (let i = 0; i < size; i++) {
      const white = Math.random() * 2 - 1;
      last = (last + 0.02 * white) / 1.02;
      data[i] = last * 3.5;
    }
    const src = audioCtx.createBufferSource();
    src.buffer = buffer;
    src.loop = true;
    const filter = audioCtx.createBiquadFilter();
    filter.type = 'lowpass';
    filter.frequency.value = 600;
    const gain = audioCtx.createGain();
    gain.gain.value = 0.05;
    src.connect(filter);
    filter.connect(gain);
    gain.connect(audioCtx.destination);
    src.start();
    _ambientNode = src;
    _ambientGain = gain;
  } catch (e) { if (window.__silent) window.__silent(e, '01f:startAmbientNoise'); }
}
function stopAmbientNoise() {
  try {
    if (_ambientNode) {
      try {
        _ambientNode.stop();
      } catch (e) { if (window.__silent) window.__silent(e, '01f:stopAmbientNoise'); }
      try {
        _ambientNode.disconnect();
      } catch (e) { if (window.__silent) window.__silent(e, '01f:stopAmbientNoise'); }
      _ambientNode = null;
    }
    if (_ambientGain) {
      try {
        _ambientGain.disconnect();
      } catch (e) { if (window.__silent) window.__silent(e, '01f:stopAmbientNoise'); }
      _ambientGain = null;
    }
  } catch (e) { if (window.__silent) window.__silent(e, '01f:stopAmbientNoise'); }
}
