/* 沉浸式冒险连续性约束：上一章完成后超过 bufferTime（默认 30 分钟）才开始下一章 →
   冒险视为「搁浅中断」，自动解锁坏结局（四个番茄必须连续推进；普通番茄轮次逻辑不受影响）。
   仅冒险 active 且已有推进(chapter>0) 时判定；老存档无 lastAdvanceAt 则跳过不误伤。 */
function immersiveCheckStale() {
  const st = appData.immersiveFocus;
  if (!st || !st.active || st.ended) return false;
  if (!st.lastAdvanceAt || !st.chapter) return false;
  const buf = appData.settings && Number(appData.settings.bufferTime) > 0 ? Number(appData.settings.bufferTime) : 30;
  const gap = (Date.now() - st.lastAdvanceAt) / 60000;
  if (gap > buf) {
    showToast(
      '⏳ 距上一章已超过 ' + Math.round(gap) + ' 分钟（>' + buf + ' 分钟）\n冒险必须连续推进，已解锁坏结局',
      true
    );
    immersiveTriggerBadEnding();
    return true;
  }
  return false;
}
