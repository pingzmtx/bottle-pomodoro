function immersiveComment(ending, mins) {
  if (ending === 'perfect') {
    if (mins >= 120) return '宇宙级专注力！章节全通，你是天生的冒险家！';
    if (mins >= 60) return '惊人的专注！剧情圆满，冒险家名不虚传！';
    return '冒险圆满通关！继续保持这份专注！';
  }
  if (ending === 'fail') return '只差最后一口气…下次终章前，记得稳住状态！';
  return '冒险折戟不丢人，收拾心情再出发！';
}
