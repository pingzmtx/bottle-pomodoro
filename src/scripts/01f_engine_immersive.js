/* 随机剧本指纹：主题 + 情节模式 + 关键变量取值 → 用做随机去重（避免近期重复剧情） */
function randomScriptFingerprint(story) {
  try {
    const ctx = story.context || {};
    const keys = Object.keys(ctx).sort();
    const parts = keys.map(function (k) {
      return k + '=' + ctx[k];
    });
    return story.theme.themeName + ':' + story.pattern.patternName + ':' + parts.join(',');
  } catch (e) {
    return '';
  }
}
/* 随机抽剧本：默认 60% 随机生成 / 40% 抽固定剧本库（含导入副本）；
   固定与随机的比例可在「设置 → 沉浸式专注 → 剧本抽取」里自行调节（immersiveFocus.fixedChance），
   固定池抽取时自动避开最近抽到过的固定副本；随机剧本也按主题+情节+内容指纹去重，
   尽量避免近期重复体验 */
function immersiveFixedChance() {
  const st = appData.immersiveFocus || {};
  const v = typeof st.fixedChance === 'number' ? st.fixedChance : 0.4;
  /* 固定上限 60%，保底 40% 走随机副本 */
  return Math.max(0, Math.min(0.6, v));
}
function immersivePickRandomScript() {
  const st = appData.immersiveFocus || {};
  if (!Array.isArray(st.recentRandom)) st.recentRandom = [];
  if (Math.random() >= immersiveFixedChance()) {
    /* 随机剧本去重：最多重试 8 次，避免与最近抽到过的随机剧情撞车 */
    let story = null;
    for (let i = 0; i < 8; i++) {
      const cand = generateStory();
      const sig = randomScriptFingerprint(cand);
      if (!sig || st.recentRandom.indexOf(sig) < 0) {
        story = cand;
        break;
      }
    }
    if (!story) story = generateStory();
    const sig2 = randomScriptFingerprint(story);
    if (sig2) {
      st.recentRandom.push(sig2);
      if (st.recentRandom.length > 8) st.recentRandom.shift();
    }
    saveData();
    return buildRandomScript(story);
  }
  let pool = immersiveFixedPool();
  if (!pool.length) return null;
  if (!Array.isArray(st.recentFixed)) st.recentFixed = [];
  /* 先剔除最近抽到过的固定副本，避免反复抽到同一本；若最近几本都抽遍（池小），
     至少兜底排除「上一本」，保证不会连续抽到同一本（池只有 1 本时除外） */
  const banned = {};
  st.recentFixed.forEach(function (id) {
    banned[id] = true;
  });
  let fresh = pool.filter(function (s) {
    return !banned[s.id];
  });
  if (!fresh.length && st.recentFixed.length && pool.length > 1) {
    const lastId = st.recentFixed[st.recentFixed.length - 1];
    fresh = pool.filter(function (s) {
      return s.id !== lastId;
    });
  }
  if (fresh.length) pool = fresh;
  const pick = pool[Math.floor(Math.random() * pool.length)];
  /* 记住这次抽中的固定副本 id（环形队列，最多记 8 个最近） */
  st.recentFixed = st.recentFixed.filter(function (id) {
    return id !== pick.id;
  });
  st.recentFixed.push(pick.id);
  if (st.recentFixed.length > 8) st.recentFixed.shift();
  saveData();
  return pick;
}
/* 用户点「进入冒险」：缓存剧本对象并初始化冒险状态（script 对象持久化，刷新后随机剧本可继续） */
